create table admins (
    id            bigint generated by default as identity primary key,
    username      varchar(64)  not null,
    password_hash varchar(100) not null,
    role_name     varchar(16)  not null default 'ADMIN',
    enabled       boolean      not null default true,
    created_at    timestamp with time zone not null default now(),
    last_login_at timestamp with time zone
);

create unique index uk_admins_username on admins (username);

create table admin_sessions (
    token_hash   varchar(64) primary key,
    admin_id     bigint      not null references admins (id) on delete cascade,
    created_at   timestamp with time zone not null default now(),
    expires_at   timestamp with time zone not null,
    last_seen_at timestamp with time zone,
    ip           varchar(64),
    user_agent   varchar(255)
);

create index idx_admin_sessions_admin_id on admin_sessions (admin_id);
create index idx_admin_sessions_expires_at on admin_sessions (expires_at);

create table songs (
    id              varchar(16) primary key,
    song_name       varchar(120) not null,
    video_url       varchar(512) not null,
    listen_duration double precision not null,
    total_duration  double precision not null,
    lyrics          text         not null,
    status          varchar(16)  not null default 'ACTIVE',
    created_by      varchar(64),
    created_at      timestamp with time zone not null default now(),
    updated_at      timestamp with time zone not null default now()
);

create index idx_songs_status on songs (status);

create table song_pitch_contours (
    song_id      varchar(16) primary key references songs (id) on delete cascade,
    encoding     varchar(16) not null,
    sample_count integer     not null,
    contour_data bytea       not null
);
